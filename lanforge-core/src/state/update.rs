//! `DeviceUpdate` — The primary mechanism for modifying Device state.
//!
//! This module defines the [`DeviceUpdate`] enum and its application logic within
//! [`DeviceTable`]. The `apply_update` method is the system's sole authority for
//! state transitions, merging rules, and administrative precedence.

use std::net::{Ipv4Addr, Ipv6Addr};
use std::sync::Arc;
use std::time::SystemTime;

use tracing::{debug, warn};

use crate::device::{
    Hostname, HostnameOrigin, IPv4State, IPv6State, Ipv6AddrOrSuffix, Origin, V4Lease, V6Lease,
    V6PrefixLease,
};
use crate::identifiers::{Duid, MacAddr};
use crate::state::DeviceTable;

// ---------------------------------------------------------------------------
// FieldUpdate
// ---------------------------------------------------------------------------

/// Represents a tri-state field update: No Change, Clear, or Set a new value.
///
/// This replaces the ambiguous `Option<Option<T>>` pattern.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize, Default)]
pub enum FieldUpdate<T> {
    /// The field should not be modified.
    #[serde(rename = "no_change")]
    #[default]
    NoChange,
    /// The field should be cleared (reset to default or `None`).
    #[serde(rename = "clear")]
    Clear,
    /// The field should be set to the provided value.
    #[serde(rename = "set")]
    Set(T),
}

impl<T> From<Option<T>> for FieldUpdate<T> {
    fn from(opt: Option<T>) -> Self {
        opt.map_or_else(|| Self::Clear, |val| Self::Set(val))
    }
}

// ---------------------------------------------------------------------------
// StaticEntry
// ---------------------------------------------------------------------------

/// Represents a persistent static configuration entry for a device.
#[derive(Debug, Clone)]
pub struct StaticEntry {
    /// The MAC address identifier.
    pub mac: MacAddr,
    /// The assigned hostname.
    pub hostname: String,
    /// The optional static IPv4 address reservation.
    pub v4_ip: Option<Ipv4Addr>,
    /// The optional static IPv6 Interface ID (suffix).
    pub v6_suffix: Option<Ipv6AddrOrSuffix>,
}

// ---------------------------------------------------------------------------
// DeviceUpdate
// ---------------------------------------------------------------------------

/// Represents an atomic state change proposed by a network protocol.
///
/// Updates are generated by workers (DHCP, NDP, SLAAC, Netlink) and processed
/// by the [`DeviceTable::apply_update`] method to maintain a consistent state.
#[derive(Debug, Clone)]
pub enum DeviceUpdate {
    /// A `DHCPv4` lease was granted or renewed.
    V4LeaseGranted {
        mac: MacAddr,
        ip: Ipv4Addr,
        expires: SystemTime,
    },

    /// A `DHCPv6` address lease (`IA_NA`) was granted or renewed.
    V6LeaseGranted {
        /// Optional MAC (resolved later via NDP if missing).
        mac: Option<MacAddr>,
        duid: Duid,
        iaid: u32,
        ip: Ipv6Addr,
        expires: SystemTime,
    },

    /// A `DHCPv6` prefix delegation (`IA_PD`) was granted or renewed.
    V6PrefixAssigned {
        mac: Option<MacAddr>,
        duid: Duid,
        iaid: u32,
        prefix: Ipv6Addr,
        len: u8,
        expires: SystemTime,
    },

    /// A SLAAC address was observed active via Neighbor Discovery (NDP).
    SlaacObserved { mac: MacAddr, addr: Ipv6Addr },

    /// A generic IPv6 neighbor event was observed.
    NdpSeen { mac: MacAddr, ip: Ipv6Addr },

    /// An IPv4 neighbor event (ARP) was observed.
    ArpSeen { mac: MacAddr, ip: Ipv4Addr },
    /// A hostname was learned via DHCP (Op12/v6).
    DhcpHostnameHint { mac: MacAddr, hostname: String },
    /// A hostname was learned via mDNS.
    MdnsHostnameHint { mac: MacAddr, hostname: String },

    /// A DUID was associated with a MAC address (e.g., during `DHCPv6` Solicit).
    DuidAssociated {
        mac: Option<MacAddr>,
        duid: Duid,
        iaid: u32,
    },

    /// Explicit field modification via CLI or HTTP API.
    CliHostUpdated {
        mac: MacAddr,
        hostname: FieldUpdate<String>,
        v4_static: FieldUpdate<Ipv4Addr>,
        v6_suffix: FieldUpdate<Ipv6AddrOrSuffix>,
        /// The administrative origin of this update.
        origin: Origin,
    },

    /// Clear all SLAAC addresses for a device (e.g., before partial re-scan).
    SlaacCleared { mac: MacAddr },

    /// Completely remove a host and its indices.
    HostRemoved { mac: MacAddr },

    /// Formally release all dynamic leases for a device.
    LeaseReleased { mac: MacAddr },

    /// An IP address was explicitly removed from the system neighbor cache.
    IpDeleted { ip: std::net::IpAddr },

    /// Local interface IP address change.
    InterfaceIpsChanged {
        ifindex: u32,
        link_local: Option<Ipv6Addr>,
        gua: Option<Ipv6Addr>,
    },

    /// Request to rebuild the high-performance DNS lookup indices.
    RebuildDnsIndices,
}

// ---------------------------------------------------------------------------
// apply_update — autoridade única de merging
// ---------------------------------------------------------------------------

impl DeviceTable {
    fn handle_v4_lease_granted(&mut self, mac: MacAddr, ip: Ipv4Addr, expires: SystemTime) -> bool {
        let dev_arc = self.get_or_insert(mac);
        let new_lease = V4Lease { ip, expires };

        match &dev_arc.v4 {
            IPv4State::Static(s_ip) if *s_ip == ip => false,
            IPv4State::Dynamic(old) if old.ip == ip && old.expires == expires => false,
            _ => {
                debug!("[state] V4 lease {} → {}", mac, ip);
                let mut dev = (*dev_arc).clone();
                dev.v4 = IPv4State::Dynamic(new_lease);
                dev.last_seen = SystemTime::now();
                self.devices.insert(mac, Arc::new(dev));
                true
            }
        }
    }

    fn handle_v6_lease_granted(
        &mut self,
        mac: Option<MacAddr>,
        duid: Duid,
        iaid: u32,
        ip: Ipv6Addr,
        expires: SystemTime,
    ) -> bool {
        let Some(m) = mac else {
            debug!("[state] V6 lease órfão → {}", ip);
            self.orphaned_v6.insert(ip, (duid, iaid, expires));
            return false;
        };

        self.duid_index.insert(duid.clone(), m);
        let dev_arc = self.get_or_insert(m);
        let new_lease = V6Lease { ip, iaid, expires };

        let mut already_correct = false;
        for state in &dev_arc.v6 {
            if let IPv6State::Dynamic(old) = state
                && old.iaid == iaid
            {
                if old.ip == ip && old.expires == expires {
                    already_correct = true;
                }
                break;
            }
        }

        if already_correct {
            return false;
        }

        let mut dev = (*dev_arc).clone();
        let mut found = false;
        for state in &mut dev.v6 {
            if let IPv6State::Dynamic(old) = state
                && old.iaid == iaid
            {
                *state = IPv6State::Dynamic(new_lease.clone());
                found = true;
                break;
            }
        }

        if !found {
            dev.v6.push(IPv6State::Dynamic(new_lease));
        }
        dev.duid = Some(duid);
        dev.last_seen = SystemTime::now();
        self.devices.insert(m, Arc::new(dev));
        true
    }

    fn handle_v6_prefix_assigned(
        &mut self,
        mac: Option<MacAddr>,
        duid: Duid,
        iaid: u32,
        prefix: Ipv6Addr,
        len: u8,
        expires: SystemTime,
    ) -> bool {
        let Some(m) = mac else {
            return false;
        };

        self.duid_index.insert(duid.clone(), m);
        let dev_arc = self.get_or_insert(m);
        let new_lease = V6PrefixLease {
            prefix,
            len,
            iaid,
            expires,
        };

        let mut already_correct = false;
        for old in &dev_arc.v6_prefixes {
            if old.iaid == iaid {
                if old.prefix == prefix && old.len == len && old.expires == expires {
                    already_correct = true;
                }
                break;
            }
        }

        if already_correct {
            return false;
        }

        let mut dev = (*dev_arc).clone();
        let mut found = false;
        for old in &mut dev.v6_prefixes {
            if old.iaid == iaid {
                *old = new_lease.clone();
                found = true;
                break;
            }
        }

        if !found {
            dev.v6_prefixes.push(new_lease);
        }
        dev.duid = Some(duid);
        dev.last_seen = SystemTime::now();
        self.devices.insert(m, Arc::new(dev));
        true
    }

    fn handle_slaac_observed(&mut self, mac: MacAddr, addr: Ipv6Addr) -> bool {
        let dev_arc = self.get_or_insert(mac);
        let mut dev = (*dev_arc).clone();
        dev.last_seen = SystemTime::now();

        if dev
            .v6
            .iter()
            .any(|s| matches!(s, IPv6State::Slaac(a) if *a == addr))
        {
            self.devices.insert(mac, Arc::new(dev));
            false
        } else {
            dev.v6.push(IPv6State::Slaac(addr));
            self.devices.insert(mac, Arc::new(dev));
            debug!("[state] SLAAC {} → {}", mac, addr);
            true
        }
    }

    fn handle_ndp_seen(&mut self, mac: MacAddr, ip: Ipv6Addr) -> bool {
        self.ndp_cache.insert(ip, (mac, SystemTime::now()));
        if let Some((duid, iaid, expires)) = self.orphaned_v6.remove(&ip) {
            self.apply_update(DeviceUpdate::V6LeaseGranted {
                mac: Some(mac),
                duid,
                iaid,
                ip,
                expires,
            });
            return true;
        }
        let dev_arc = self.get_or_insert(mac);
        let mut dev = (*dev_arc).clone();
        dev.last_seen = SystemTime::now();
        self.devices.insert(mac, Arc::new(dev));
        false
    }

    fn handle_arp_seen(&mut self, mac: MacAddr, ip: Ipv4Addr) -> bool {
        let dev_arc = self.get_or_insert(mac);
        let mut dev = (*dev_arc).clone();
        dev.last_seen = SystemTime::now();

        if dev.seen_v4.contains(&ip) {
            self.devices.insert(mac, Arc::new(dev));
            false
        } else {
            dev.seen_v4.push(ip);
            self.devices.insert(mac, Arc::new(dev));
            true
        }
    }

    fn handle_hostname_hint(
        &mut self,
        mac: MacAddr,
        hostname: String,
        origin: HostnameOrigin,
    ) -> bool {
        let dev_arc = self.get_or_insert(mac);
        if origin >= dev_arc.hostname.origin && dev_arc.hostname.name != hostname {
            let mut dev = (*dev_arc).clone();
            dev.hostname = Hostname {
                name: hostname,
                origin,
            };
            self.devices.insert(mac, Arc::new(dev));
            return true;
        }
        false
    }

    fn handle_duid_associated(&mut self, mac: Option<MacAddr>, duid: &Duid, iaid: u32) -> bool {
        let Some(m) = mac else {
            return false;
        };

        let mut changed = false;
        self.duid_index.insert(duid.clone(), m);
        let dev_arc = self.get_or_insert(m);
        if dev_arc.duid.as_ref() != Some(duid) {
            let mut dev = (*dev_arc).clone();
            dev.duid = Some(duid.clone());
            self.devices.insert(m, Arc::new(dev));
            changed = true;
        }

        // Resolve órfãos que estavam esperando por este DUID+IAID
        let mut resolved = Vec::new();
        for (&ip, (o_duid, o_iaid, _)) in &self.orphaned_v6 {
            if *o_duid == *duid && *o_iaid == iaid {
                resolved.push(ip);
            }
        }

        for ip in resolved {
            if let Some((duid, iaid, expires)) = self.orphaned_v6.remove(&ip) {
                debug!(
                    "[state] Resolvendo órfão via DuidAssociated: {} -> {}",
                    ip, m
                );
                self.apply_update(DeviceUpdate::V6LeaseGranted {
                    mac: Some(m),
                    duid,
                    iaid,
                    ip,
                    expires,
                });
                changed = true;
            }
        }
        changed
    }

    fn handle_cli_host_updated(
        &mut self,
        mac: MacAddr,
        hostname: FieldUpdate<String>,
        v4_static: FieldUpdate<Ipv4Addr>,
        v6_suffix: FieldUpdate<Ipv6AddrOrSuffix>,
        origin: Origin,
    ) -> bool {
        let dev_arc = self.get_or_insert(mac);
        if dev_arc.origin == Origin::Toml {
            warn!("Tentativa de modificar device estático do TOML: {}", mac);
            return false;
        }

        let mut dev = (*dev_arc).clone();
        let mut changed = false;
        match hostname {
            FieldUpdate::Set(hn) => {
                if dev.hostname.name != hn || dev.hostname.origin != HostnameOrigin::Static {
                    dev.hostname = Hostname {
                        name: hn,
                        origin: HostnameOrigin::Static,
                    };
                    changed = true;
                }
            }
            FieldUpdate::Clear => {
                if !dev.hostname.name.is_empty() {
                    dev.hostname = Hostname::default();
                    changed = true;
                }
            }
            FieldUpdate::NoChange => {}
        }

        match v4_static {
            FieldUpdate::Set(ip) => {
                if dev.v4 != IPv4State::Static(ip) {
                    dev.v4 = IPv4State::Static(ip);
                    changed = true;
                }
            }
            FieldUpdate::Clear => {
                if dev.v4 != IPv4State::None {
                    dev.v4 = IPv4State::None;
                    changed = true;
                }
            }
            FieldUpdate::NoChange => {}
        }

        match v6_suffix {
            FieldUpdate::Set(suf) => {
                let new_state = IPv6State::Static(suf);
                let mut found = false;
                for state in &mut dev.v6 {
                    if matches!(state, IPv6State::Static(_)) {
                        if *state != new_state {
                            *state = new_state.clone();
                            changed = true;
                        }
                        found = true;
                        break;
                    }
                }
                if !found {
                    dev.v6.push(new_state);
                    changed = true;
                }
            }
            FieldUpdate::Clear => {
                let initial_len = dev.v6.len();
                dev.v6.retain(|s| !matches!(s, IPv6State::Static(_)));
                if dev.v6.len() != initial_len {
                    changed = true;
                }
            }
            FieldUpdate::NoChange => {}
        }

        if changed {
            dev.origin = origin;
            dev.managed_at = Some(SystemTime::now());
            dev.last_seen = SystemTime::now();

            // Sync static_entries for legacy components
            let hostname_str = dev.hostname.name.clone();
            let v4_ip = match dev.v4 {
                IPv4State::Static(ip) => Some(ip),
                _ => None,
            };
            let v6_suffix_opt = dev.v6.iter().find_map(|s| {
                if let IPv6State::Static(suffix) = s {
                    Some(suffix.clone())
                } else {
                    None
                }
            });

            self.static_entries.insert(
                mac,
                StaticEntry {
                    mac,
                    hostname: hostname_str,
                    v4_ip,
                    v6_suffix: v6_suffix_opt,
                },
            );

            self.devices.insert(mac, Arc::new(dev));
        }
        changed
    }

    fn handle_slaac_cleared(&mut self, mac: MacAddr) -> bool {
        if let Some(dev_arc) = self.devices.get(&mac) {
            let mut dev = (**dev_arc).clone();
            let initial_len = dev.v6.len();
            dev.v6.retain(|s| !matches!(s, IPv6State::Slaac(_)));
            if dev.v6.len() != initial_len {
                self.devices.insert(mac, Arc::new(dev));
                return true;
            }
        }
        false
    }

    fn handle_host_removed(&mut self, mac: MacAddr) -> bool {
        let changed_dev = if let Some(dev) = self.devices.remove(&mac) {
            if let Some(duid) = &dev.duid {
                self.duid_index.remove(duid);
            }
            true
        } else {
            false
        };
        let changed_static = self.static_entries.remove(&mac).is_some();
        changed_dev || changed_static
    }

    fn handle_lease_released(&mut self, mac: MacAddr) -> bool {
        if let Some(dev_arc) = self.devices.get(&mac) {
            let mut dev = (**dev_arc).clone();
            let changed_v4 = if matches!(dev.v4, IPv4State::None) {
                false
            } else {
                dev.v4 = IPv4State::None;
                true
            };
            let initial_v6_len = dev.v6.len();
            dev.v6.retain(|s| !matches!(s, IPv6State::Dynamic(_)));
            let changed_v6 = dev.v6.len() != initial_v6_len;

            if changed_v4 || changed_v6 {
                self.devices.insert(mac, Arc::new(dev));
                return true;
            }
        }
        false
    }

    fn handle_ip_deleted(&mut self, ip: std::net::IpAddr) -> bool {
        let changed_ndp = if let std::net::IpAddr::V6(ip6) = ip
            && self.ndp_cache.remove(&ip6).is_some()
        {
            true
        } else {
            false
        };

        let mut changed_devices = false;
        let mut updates = Vec::new();

        for (&mac, dev_arc) in &self.devices {
            let mut dev = (**dev_arc).clone();
            let mut local_changed = false;
            match ip {
                std::net::IpAddr::V6(ip6) => {
                    let initial_len = dev.v6.len();
                    dev.v6
                        .retain(|s| !matches!(s, IPv6State::Slaac(a) if *a == ip6));
                    if dev.v6.len() != initial_len {
                        local_changed = true;
                    }
                }
                std::net::IpAddr::V4(ip4) => {
                    if let Some(pos) = dev.seen_v4.iter().position(|&x| x == ip4) {
                        dev.seen_v4.remove(pos);
                        local_changed = true;
                    }
                }
            }
            if local_changed {
                updates.push((mac, Arc::new(dev)));
                changed_devices = true;
            }
        }

        for (mac, new_dev) in updates {
            self.devices.insert(mac, new_dev);
        }

        changed_ndp || changed_devices
    }

    fn handle_interface_ips_changed(
        &mut self,
        ifindex: u32,
        link_local: Option<Ipv6Addr>,
        gua: Option<Ipv6Addr>,
    ) -> bool {
        use super::InterfaceState;
        let entry = self.interface_ips.entry(ifindex).or_default();
        if entry.link_local == link_local && entry.gua == gua {
            false
        } else {
            *entry = InterfaceState { link_local, gua };
            debug!(
                "[state] Interface {} IPs updated: LL={:?}, GUA={:?}",
                ifindex, link_local, gua
            );
            true
        }
    }
}

impl DeviceTable {
    /// Applies a proposed state change to the device table.
    ///
    /// Returns `true` if the internal state was effectively altered. If `true`,
    /// the caller is responsible for emitting a `LanforgeEvent::DeviceTableDirty`
    /// event on the system bus.
    ///
    /// ## Precedence and Merging Rules
    ///
    /// - **Hostnames**: Static configuration (`Toml`/`Cli`) always overrides dynamic hints.
    /// - **IPv4 Addresses**: Static reservations take priority over `DHCPv4` leases.
    /// - **Orphan Handling**: `DHCPv6` leases without a MAC are cached until an `NDP`
    ///   event allows resolution.
    ///
    /// ```mermaid
    /// flowchart TD
    ///     Update[DeviceUpdate Received] --> Resolve{Has MAC?}
    ///     Resolve -- No --> Orphan[Add to Orphaned Cache]
    ///     Resolve -- Yes --> Lookup[Lookup Device in HashMap]
    ///     Lookup --> Create[Create if Discovered]
    ///     Create --> Merge{Check Precedence}
    ///     Merge -- Static Wins --> Skip[No Change]
    ///     Merge -- Update Allowed --> Apply[Modify Fields]
    ///     Apply --> Indices[Rebuild DNS Hot-Path Indices]
    ///     Indices --> Return[Return Changed=true]
    /// ```
    pub fn apply_update(&mut self, update: DeviceUpdate) -> bool {
        let changed = match update {
            DeviceUpdate::V4LeaseGranted { mac, ip, expires } => {
                self.handle_v4_lease_granted(mac, ip, expires)
            }
            DeviceUpdate::V6LeaseGranted {
                mac,
                duid,
                iaid,
                ip,
                expires,
            } => self.handle_v6_lease_granted(mac, duid, iaid, ip, expires),
            DeviceUpdate::V6PrefixAssigned {
                mac,
                duid,
                iaid,
                prefix,
                len,
                expires,
            } => self.handle_v6_prefix_assigned(mac, duid, iaid, prefix, len, expires),
            DeviceUpdate::SlaacObserved { mac, addr } => self.handle_slaac_observed(mac, addr),
            DeviceUpdate::NdpSeen { mac, ip } => self.handle_ndp_seen(mac, ip),
            DeviceUpdate::ArpSeen { mac, ip } => self.handle_arp_seen(mac, ip),
            DeviceUpdate::DhcpHostnameHint { mac, hostname } => {
                self.handle_hostname_hint(mac, hostname, HostnameOrigin::Dhcp)
            }
            DeviceUpdate::MdnsHostnameHint { mac, hostname } => {
                self.handle_hostname_hint(mac, hostname, HostnameOrigin::Mdns)
            }
            DeviceUpdate::DuidAssociated { mac, duid, iaid } => {
                self.handle_duid_associated(mac, &duid, iaid)
            }
            DeviceUpdate::CliHostUpdated {
                mac,
                hostname,
                v4_static,
                v6_suffix,
                origin,
            } => self.handle_cli_host_updated(mac, hostname, v4_static, v6_suffix, origin),
            DeviceUpdate::SlaacCleared { mac } => self.handle_slaac_cleared(mac),
            DeviceUpdate::HostRemoved { mac } => self.handle_host_removed(mac),
            DeviceUpdate::LeaseReleased { mac } => self.handle_lease_released(mac),
            DeviceUpdate::IpDeleted { ip } => self.handle_ip_deleted(ip),
            DeviceUpdate::InterfaceIpsChanged {
                ifindex,
                link_local,
                gua,
            } => self.handle_interface_ips_changed(ifindex, link_local, gua),
            DeviceUpdate::RebuildDnsIndices => {
                self.rebuild_dns_indices();
                false
            }
        };

        // ⚡ RECONSTRUÇÃO AUTOMÁTICA DOS ÍNDICES (Otimização do DNS)
        if changed {
            self.rebuild_dns_indices();
        }

        changed
    }

    // -----------------------------------------------------------------------
    // Inicialização (config estática)
    // -----------------------------------------------------------------------

    /// Insere um dispositivo estático já validado.
    /// Chamado pela orquestração durante o startup.
    pub fn add_static_device(
        &mut self,
        mac: MacAddr,
        hostname: String,
        v4_ip: Option<Ipv4Addr>,
        v6_suffix: Option<Ipv6AddrOrSuffix>,
    ) {
        let static_entry = StaticEntry {
            mac,
            hostname: hostname.clone(),
            v4_ip,
            v6_suffix: v6_suffix.clone(),
        };

        self.static_entries.insert(mac, static_entry);

        let dev_arc = self.get_or_insert(mac);
        let mut dev = (*dev_arc).clone();
        dev.hostname = Hostname {
            name: hostname,
            origin: HostnameOrigin::Static,
        };

        if let Some(ip) = v4_ip {
            dev.v4 = IPv4State::Static(ip);
        }
        if let Some(suf) = v6_suffix {
            let new_state = IPv6State::Static(suf);
            let mut found = false;
            for state in &mut dev.v6 {
                if matches!(state, IPv6State::Static(_)) {
                    *state = new_state.clone();
                    found = true;
                    break;
                }
            }
            if !found {
                dev.v6.push(new_state);
            }
        }
        dev.origin = Origin::Toml;
        self.devices.insert(mac, Arc::new(dev));
    }
}
